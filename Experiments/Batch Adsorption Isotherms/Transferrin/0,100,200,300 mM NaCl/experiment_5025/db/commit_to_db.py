def extract_metadata(extra_fields):
    metadata = {}
    normalized_extra = {normalize_key(k): (k, v) for k, v in extra_fields.items()}

    for elab_name, db_name in FIELD_MAPPING.items():
        field_obj = None

        if elab_name in extra_fields:
            field_obj = extra_fields.get(elab_name)
        else:
            hit = normalized_extra.get(normalize_key(elab_name))
            if hit:
                _, field_obj = hit

        if not isinstance(field_obj, dict):
            continue

        value = field_obj.get("value")
        target_type = infer_schema_type(db_name)
        coerced = coerce_value(value, target_type)

        if coerced is not None:
            metadata[db_name] = coerced
        elif value not in (None, ""):
            metadata[db_name] = value

    return metadata


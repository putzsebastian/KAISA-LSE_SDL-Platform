def coerce_value(value, target_type):
    if value is None:
        return None
    if target_type == "string":
        return str(value)
    if target_type == "integer":
        num = parse_numeric(value)
        return int(num) if num is not None else None
    if target_type == "number":
        return parse_numeric(value)
    return value


#!/usr/bin/env python3
"""
Report Generator with eLabFTW Integration and Proper Plot Handling
Generated for Template ID: 278

This script:
1. Loads experiment data from eLabFTW API
2. Finds and processes selected plot files
3. Uploads plots and retrieves eLabFTW longnames
4. Replaces placeholders in HTML template with proper eLabFTW URLs
5. Updates experiment body with report

Template Fields Configured: 27
Selected Plots: 1
"""

import json
import os
import re
import sys
import argparse
import requests
from pathlib import Path
from datetime import datetime
import mimetypes
import time

# Configuration
ELAB_API_BASE = "https://<ELAB_HOST>"
TEMPLATE_FILENAME = "report_template_278.html"

# Field mapping from eLabFTW to template placeholders
FIELD_MAPPING = {
    "Buffer": "BUFFER",
    "Salt Name": "SALT_NAME",
    "Process ID": "PROCESS_ID",
    "Pump Speed": "PUMP_SPEED",
    "Replicates": "REPLICATES",
    "Resin Mass": "RESIN_MASS",
    "Ligand Name": "LIGAND_NAME",
    "Total volume": "TOTAL_VOLUME",
    "Venting time": "VENTING_TIME",
    "Pump Duration": "PUMP_DURATION",
    "Incubation Time": "INCUBATION_TIME",
    "Salt concentrations": "SALT_CONCENTRATIONS",
    "Equilibration Cycles": "EQUILIBRATION_CYCLES",
    "Equilibration Volume": "EQUILIBRATION_VOLUME",
    "Ligand concentrations": "LIGAND_CONCENTRATIONS",
    "Incubation Temperature": "INCUBATION_TEMPERATURE",
    "Measurement Wavelength": "MEASUREMENT_WAVELENGTH",
    "Calibration Curve Slope": "CALIBRATION_CURVE_SLOPE",
    "Salt concentration unit": "SALT_CONCENTRATION_UNIT",
    "Shaker Speed Incubation": "SHAKER_SPEED_INCUBATION",
    "Salt Stock Concentration": "SALT_STOCK_CONCENTRATION",
    "Ligand concentration unit": "LIGAND_CONCENTRATION_UNIT",
    "Ligand Stock Concentration": "LIGAND_STOCK_CONCENTRATION",
    "Calibration Curve Intercept": "CALIBRATION_CURVE_INTERCEPT",
    "Equilibration Cycle Duration": "EQUILIBRATION_CYCLE_DURATION",
    "Number of salt concentrations": "NUMBER_OF_SALT_CONCENTRATIONS",
    "Number of ligand concentrations": "NUMBER_OF_LIGAND_CONCENTRATIONS",
}
# Selected plots information
SELECTED_PLOTS = [{"display_name": "Plot generated by analysis_script_15.py", "filename": "loading_isotherms_{ID}.png", "type": "isotherm_plot"}]

# Default eLabFTW API key (when called from app)
DEFAULT_ELAB_TOKEN = os.environ.get('ELAB_API_TOKEN', None)

class eLabFTWReportGenerator:
    def __init__(self, elab_token, experiment_id):
        self.elab_token = elab_token
        self.experiment_id = experiment_id
        self.headers = {
            "Authorization": elab_token,
            "Content-Type": "application/json"
        }
        self.session = requests.Session()
        self.session.headers.update(self.headers)
    
    def get_experiment_data(self):
        """Get experiment data from eLabFTW API"""
        url = f"{ELAB_API_BASE}/api/v2/experiments/{self.experiment_id}"
        
        try:
            print(f"INFO: Getting experiment data from: {url}")
            print(f"INFO: Using API token: {self.elab_token[:20] if len(self.elab_token) > 20 else 'TOKEN_TOO_SHORT'}...")
            
            response = self.session.get(url)
            print(f"INFO: Response status: {response.status_code}")
            
            if response.status_code != 200:
                print(f"ERROR: Failed to get experiment data: {response.text}")
                response.raise_for_status()
                
            experiment_data = response.json()
            print(f"SUCCESS: Successfully retrieved experiment data (title: {experiment_data.get('title', 'N/A')})")
            return experiment_data
            
        except requests.RequestException as e:
            print(f"ERROR: HTTP Error getting experiment data: {e}")
            if hasattr(e, 'response') and e.response is not None:
                print(f"   Response status: {e.response.status_code}")
                print(f"   Response text: {e.response.text}")
            raise Exception(f"Failed to get experiment data: {e}")
    
    def extract_field_values(self, experiment_data):
        """Extract field values for template replacement"""
        values = {}
        
        try:
            # Get metadata from eLabFTW
            metadata = experiment_data.get('metadata_decoded', {})
            extra_fields = metadata.get('extra_fields', {})
            
            # Map eLabFTW fields to template placeholders (ONLY configured fields)
            for field_name, placeholder in FIELD_MAPPING.items():
                if field_name in extra_fields:
                    field_data = extra_fields[field_name]
                    if isinstance(field_data, dict):
                        field_value = field_data.get('value', '')
                        # Only add non-empty values
                        if field_value and str(field_value).strip():
                            values[placeholder] = str(field_value).strip()
                        else:
                            values[placeholder] = 'Not specified'
                    else:
                        values[placeholder] = str(field_data)
                else:
                    values[placeholder] = 'Field not found'
                    print(f"Warning: eLabFTW field '{field_name}' not found in experiment metadata")
            
            # Add basic experiment metadata (always available)
            values['EXPERIMENT_ID'] = str(self.experiment_id)
            values['EXPERIMENT_TITLE'] = experiment_data.get('title', f'Experiment {self.experiment_id}')  
            values['EXPERIMENT_DATE'] = experiment_data.get('date', experiment_data.get('created_at', ''))
            values['REPORT_DATE'] = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
            
            print(f"Extracted {len(values)} field values from eLabFTW")
            for key, value in values.items():
                print(f"  {key}: {value}")
            
        except Exception as e:
            print(f"Warning: Error extracting field values: {e}")
            # Still provide basic values
            values = {
                'EXPERIMENT_ID': str(self.experiment_id),
                'EXPERIMENT_TITLE': f'Experiment {self.experiment_id}',
                'REPORT_DATE': datetime.now().strftime('%Y-%m-%d %H:%M:%S')
            }
        
        return values
    
    def find_selected_plot_files(self, results_folder='../results'):
        """Find the actual plot files based on selected plots"""
        plot_files = []
        results_path = Path(results_folder)
        
        if not results_path.exists():
            print(f"Results folder not found: {results_folder}")
            return plot_files
        
        print(f"Looking for {len(SELECTED_PLOTS)} selected plots in {results_folder}")
        
        for i, plot_info in enumerate(SELECTED_PLOTS):
            expected_filename = plot_info['filename']
            
            # Replace template_id with experiment_id in filename for dynamic matching
            # This handles cases where template uses template_id but analysis generates with experiment_id
            expected_filename = expected_filename.replace('_225', f'_{self.experiment_id}')
            
            print(f"  Searching for plot {i+1}: {expected_filename}")
            
            # Try to find exact match first
            exact_path = results_path / expected_filename
            if exact_path.exists():
                plot_files.append({
                    'path': exact_path,
                    'info': plot_info,
                    'found_as': 'exact_match',
                    'plot_number': i + 1
                })
                print(f"    Found exact match: {exact_path}")
                continue
            
            # Try pattern matching for files with ID placeholders
            search_patterns = [
                expected_filename.replace('[ID]', f'{self.experiment_id}'),
                expected_filename.replace('{ID}', f'{self.experiment_id}'),
                f'*{expected_filename}*',
                f'*{Path(expected_filename).stem}*{Path(expected_filename).suffix}'
            ]
            
            found = False
            for pattern in search_patterns:
                matching_files = list(results_path.glob(pattern))
                if matching_files:
                    plot_files.append({
                        'path': matching_files[0],  # Take first match
                        'info': plot_info,
                        'found_as': 'pattern_match',
                        'pattern': pattern,
                        'plot_number': i + 1
                    })
                    print(f"    Found with pattern '{pattern}': {matching_files[0]}")
                    found = True
                    break
            
            if not found:
                print(f"    Plot file not found: {expected_filename}")
                # Add placeholder entry
                plot_files.append({
                    'path': None,
                    'info': plot_info,
                    'found_as': 'not_found',
                    'plot_number': i + 1
                })
        
        return plot_files
    
    def upload_file_to_elab_and_get_longname(self, file_path):
        """Upload file to eLabFTW experiment and return longname for embedding"""
        url = f"{ELAB_API_BASE}/api/v2/experiments/{self.experiment_id}/uploads"
        
        try:
            with open(file_path, 'rb') as f:
                files = {'file': (file_path.name, f, mimetypes.guess_type(str(file_path))[0])}
                
                # Use different headers for file upload (remove Content-Type for multipart)
                upload_headers = {"Authorization": self.elab_token}
                
                response = requests.post(url, files=files, headers=upload_headers)
                response.raise_for_status()
                
                print(f"Uploaded {file_path.name} to eLabFTW")
                
                # Small delay to ensure upload is processed
                time.sleep(0.5)
                
                # Now retrieve the longname for this uploaded file
                uploads_url = f"{ELAB_API_BASE}/api/v2/experiments/{self.experiment_id}/uploads"
                uploads_response = self.session.get(uploads_url)
                uploads_response.raise_for_status()
                
                uploads_data = uploads_response.json()
                for upload in uploads_data:
                    if upload.get('real_name') == file_path.name:
                        longname = upload.get('long_name')
                        print(f"Retrieved longname for {file_path.name}: {longname}")
                        return longname
                
                print(f"WARNING: Uploaded {file_path.name} but couldn't retrieve longname")
                return file_path.name  # fallback to filename
                    
        except Exception as e:
            print(f"ERROR: Failed to upload {file_path.name}: {e}")
            return None
    
    def load_analysis_results(self, results_folder='../results'):
        """Load analysis results if available"""
        results_path = Path(results_folder)
        
        # Try multiple patterns for analysis results
        analysis_patterns = [
            f'*analysis*{self.experiment_id}*.json',
            f'analysis_results*{self.experiment_id}*.json',
            f'*results*{self.experiment_id}*.json',
            'analysis_results*.json',
            '*analysis*.json'
        ]
        
        for pattern in analysis_patterns:
            analysis_files = list(results_path.glob(pattern))
            if analysis_files:
                try:
                    with open(analysis_files[0], 'r') as f:
                        results = json.load(f)
                        print(f"Loaded analysis results from: {analysis_files[0]}")
                        return results
                except Exception as e:
                    print(f"Error loading {analysis_files[0]}: {e}")
        
        print("No analysis results found")
        return None
    
    def create_plots_section_with_longnames(self, plot_files, upload_files=True):
        """Create HTML section for selected plots with proper eLabFTW URLs"""
        if not plot_files:
            return '<p>No plots selected</p>'
        
        plots_html = ''
        uploaded_plots = []
        
        for plot_data in plot_files:
            plot_info = plot_data['info']
            plot_path = plot_data['path']
            plot_number = plot_data['plot_number']
            
            if plot_path and plot_path.exists():
                img_src = plot_path.name  # Default fallback
                longname = None
                
                if upload_files:
                    # Upload and get longname for proper eLabFTW URL
                    longname = self.upload_file_to_elab_and_get_longname(plot_path)
                    if longname:
                        # Use eLabFTW's proper download URL format
                        img_src = f"app/download.php?name={plot_path.name}&f={longname}&storage=1"
                        uploaded_plots.append(plot_path.name)
                    else:
                        # Fallback to filename only
                        img_src = plot_path.name
                
                plots_html += f'''
                <div class="plot-container" id="plot-section-{plot_number}">
                    <h4>{plot_info['display_name']}</h4>
                    <div style="text-align: center; margin: 20px 0;">
                        <img src="{img_src}" alt="{plot_info['display_name']}" style="max-width: 100%; height: auto; border-radius: 8px; box-shadow: 0 4px 8px rgba(0,0,0,0.1);">
                    </div>
                    <p style="color: #666; font-size: 0.9em; text-align: center; margin-top: 10px;">
                        Figure {plot_number}: {plot_info['display_name']}
                        <br><small>{plot_info.get('description', '')}</small>
                    </p>
                </div>
                '''
            else:
                # Plot not found - show placeholder
                plots_html += f'''
                <div class="plot-container" id="plot-section-{plot_number}" style="background: #fff3cd; border: 1px solid #ffeaa7; padding: 20px; border-radius: 8px; margin: 20px 0;">
                    <h4>{plot_info['display_name']}</h4>
                    <p style="color: #856404; text-align: center; margin: 0;">
                        WARNING: Plot file not available: {plot_info['filename']}
                    </p>
                </div>
                '''
        
        return plots_html, uploaded_plots
    
    def upload_additional_files(self, results_folder='../results', uploaded_plots=None):
        """Upload other result files to eLabFTW"""
        uploaded_plots = uploaded_plots or []
        uploaded_files = []
        results_path = Path(results_folder)
        
        if not results_path.exists():
            return uploaded_files
        
        # Look for and upload other result files
        result_files = []
        for pattern in ['*.json', '*.csv', '*.xlsx', '*.txt', '*.pdf']:
            result_files.extend(results_path.glob(pattern))
        
        for result_file in result_files:
            # Skip if it's already a plot we uploaded
            if result_file.name not in uploaded_plots:
                try:
                    with open(result_file, 'rb') as f:
                        files = {'file': (result_file.name, f, mimetypes.guess_type(str(result_file))[0])}
                        upload_headers = {"Authorization": self.elab_token}
                        url = f"{ELAB_API_BASE}/api/v2/experiments/{self.experiment_id}/uploads"
                        
                        response = requests.post(url, files=files, headers=upload_headers)
                        response.raise_for_status()
                        
                        uploaded_files.append(result_file.name)
                        print(f"Uploaded additional file: {result_file.name}")
                        
                except Exception as e:
                    print(f"ERROR: Failed to upload {result_file.name}: {e}")
        
        return uploaded_files
    
    def update_experiment_body(self, report_html):
        """Update experiment body with generated report"""
        url = f"{ELAB_API_BASE}/api/v2/experiments/{self.experiment_id}"
        
        try:
            # Debug: Test connection first
            print(f"INFO: Testing eLabFTW connection to: {ELAB_API_BASE}")
            print(f"INFO: API token starts with: {self.elab_token[:20] if len(self.elab_token) > 20 else 'TOKEN_TOO_SHORT'}...")
            print(f"INFO: Experiment ID: {self.experiment_id}")
            
            # First test if we can read the experiment
            test_response = self.session.get(url)
            print(f"INFO: GET test status: {test_response.status_code}")
            if test_response.status_code != 200:
                print(f"ERROR: Cannot read experiment: {test_response.text}")
                return False
            
            # Now try the update
            data = {"body": report_html}
            print(f"INFO: Updating experiment body (length: {len(report_html)} characters)")
            response = self.session.patch(url, json=data)
            
            print(f"INFO: PATCH response status: {response.status_code}")
            if response.status_code != 200:
                print(f"ERROR: PATCH failed with response: {response.text}")
                response.raise_for_status()
            
            print(f"SUCCESS: Updated experiment {self.experiment_id} with report")
            return True
            
        except requests.exceptions.RequestException as e:
            print(f"ERROR: HTTP Error updating experiment body: {e}")
            if hasattr(e, 'response') and e.response is not None:
                print(f"   Response status: {e.response.status_code}")
                print(f"   Response text: {e.response.text}")
            return False
        except Exception as e:
            print(f"ERROR: General error updating experiment body: {e}")
            import traceback
            traceback.print_exc()
            return False
    
    def generate_report(self, template_path=None, results_folder='../results', upload_files=True):
        """Generate complete report with selected plots and proper eLabFTW integration"""
        print(f"Generating report for experiment {self.experiment_id}")
        print(f"Template fields configured: {len(FIELD_MAPPING)}")
        print(f"Selected plots: {len(SELECTED_PLOTS)}")
        
        # Use default template path if not provided
        if template_path is None:
            template_path = Path(__file__).parent / TEMPLATE_FILENAME
        
        # Load template
        try:
            with open(template_path, 'r', encoding='utf-8') as f:
                template_content = f.read()
                print(f"SUCCESS: Loaded template: {template_path}")
        except FileNotFoundError:
            raise Exception(f"Template file not found: {template_path}")
        
        # Get experiment data
        print("Loading experiment data from eLabFTW...")
        experiment_data = self.get_experiment_data()
        
        # Extract field values
        print("Extracting field values...")
        field_values = self.extract_field_values(experiment_data)
        
        # Load analysis results
        print("Loading analysis results...")
        analysis_results = self.load_analysis_results(results_folder)
        
        # Find selected plot files
        print("Finding selected plot files...")
        plot_files = self.find_selected_plot_files(results_folder)
        found_plots = [p for p in plot_files if p['found_as'] != 'not_found']
        print(f"Found {len(found_plots)}/{len(SELECTED_PLOTS)} selected plots")
        
        # Create plots section HTML with proper eLabFTW URLs
        print("Creating plots section with eLabFTW longnames...")
        plots_section_html, uploaded_plot_names = self.create_plots_section_with_longnames(plot_files, upload_files)
        
        # Prepare replacement values - ONLY use configured fields + plots
        replacements = {
            **field_values,  # Only configured eLabFTW fields
            'PLOTS_SECTION': plots_section_html,
            'ELAB_EXPERIMENT_URL': f"{ELAB_API_BASE}/experiments/view/{self.experiment_id}"
        }
        
        # Add specific plot placeholders for numbered plots (as used in template)
        for plot_data in plot_files:
            plot_number = plot_data['plot_number']
            plot_path = plot_data['path']
            
            if plot_path and plot_path.exists():
                if upload_files:
                    # Get the longname and create proper eLabFTW URL
                    longname = self.upload_file_to_elab_and_get_longname(plot_path)
                    if longname:
                        img_tag = f'<img src="app/download.php?name={plot_path.name}&f={longname}&storage=1" alt="{plot_data["info"]["display_name"]}" style="max-width: 100%; height: auto; border-radius: 8px;">'
                    else:
                        img_tag = f'<img src="{plot_path.name}" alt="{plot_data["info"]["display_name"]}" style="max-width: 100%; height: auto; border-radius: 8px;">'
                else:
                    img_tag = f'<img src="{plot_path.name}" alt="{plot_data["info"]["display_name"]}" style="max-width: 100%; height: auto; border-radius: 8px;">'
                
                replacements[f'PLOT_{plot_number}'] = img_tag
            else:
                replacements[f'PLOT_{plot_number}'] = f'<div style="color: #856404; text-align: center; padding: 20px; background: #fff3cd; border-radius: 8px;">WARNING: Plot not found: {plot_data["info"]["filename"]}</div>'
        
        # Add analysis results if available (dynamic based on what's found)
        if analysis_results:
            print(f"Including analysis results: {list(analysis_results.keys())}")
            # Dynamically add any keys from analysis results
            for key, value in analysis_results.items():
                placeholder = key.upper().replace(' ', '_').replace('-', '_')
                placeholder = re.sub(r'[^A-Z0-9_]', '', placeholder)
                if isinstance(value, (int, float)):
                    if isinstance(value, float):
                        replacements[placeholder] = f"{value:.6f}"
                    else:
                        replacements[placeholder] = str(value)
                else:
                    replacements[placeholder] = str(value)
        
        # Replace placeholders in template
        print(f"Replacing {len(replacements)} placeholders...")
        report_html = template_content
        replacements_made = 0
        
        for placeholder, value in replacements.items():
            pattern = r'\[\[' + placeholder + r'\]\]'
            old_html = report_html
            report_html = re.sub(pattern, lambda m: str(value), report_html)
            if old_html != report_html:
                replacements_made += 1
                value_preview = str(value)[:50] + ('...' if len(str(value)) > 50 else '')
                print(f"  {placeholder} -> {value_preview}")
        
        print(f"Made {replacements_made} placeholder replacements")
        
        # Upload additional files to eLabFTW if requested
        additional_uploaded = []
        if upload_files:
            print("Uploading additional files to eLabFTW...")
            additional_uploaded = self.upload_additional_files(results_folder, uploaded_plot_names)
        
        # Update experiment body
        print("Updating experiment body in eLabFTW...")
        self.update_experiment_body(report_html)
        
        # Save local copy
        report_file = Path(results_folder) / f'report_{self.experiment_id}.html'
        report_file.parent.mkdir(parents=True, exist_ok=True)
        with open(report_file, 'w', encoding='utf-8') as f:
            f.write(report_html)
        
        total_uploaded = len(uploaded_plot_names) + len(additional_uploaded)
        
        print(f"\nReport generation complete!")
        print(f"   Local report: {report_file}")
        print(f"   Template fields: {len(FIELD_MAPPING)}")
        print(f"   Selected plots: {len(SELECTED_PLOTS)} ({len(found_plots)} found)")
        print(f"   Plot files uploaded: {len(uploaded_plot_names)}")
        print(f"   Additional files uploaded: {len(additional_uploaded)}")
        print(f"   Placeholders replaced: {replacements_made}")
        print(f"   eLabFTW: {ELAB_API_BASE}/experiments/view/{self.experiment_id}")
        
        return {
            'success': True,
            'report_file': str(report_file),
            'experiment_id': self.experiment_id,
            'template_fields_configured': len(FIELD_MAPPING),
            'placeholders_replaced': replacements_made,
            'selected_plots': len(SELECTED_PLOTS),
            'plots_found': len(found_plots),
            'plot_files_uploaded': len(uploaded_plot_names),
            'additional_files_uploaded': len(additional_uploaded),
            'total_files_uploaded': total_uploaded,
            'elab_updated': True
        }


def main():
    """Command line interface"""
    parser = argparse.ArgumentParser(description='Generate eLabFTW report with proper plot integration')
    parser.add_argument('experiment_id', help='eLabFTW experiment ID')
    parser.add_argument('--elab-token', help='eLabFTW API token (or set ELAB_API_TOKEN env var)')
    parser.add_argument('--template', help='Custom template file path')
    parser.add_argument('--results-folder', default='../results', help='Results folder path')
    parser.add_argument('--no-upload', action='store_true', help='Skip file uploads to eLabFTW')
    
    args = parser.parse_args()
    
    # Get API token from argument, environment, or fail
    elab_token = args.elab_token or DEFAULT_ELAB_TOKEN
    if not elab_token:
        print("ERROR: eLabFTW API token required")
        print("   Provide via --elab-token argument or set ELAB_API_TOKEN environment variable")
        return 1
    
    try:
        generator = eLabFTWReportGenerator(elab_token, args.experiment_id)
        result = generator.generate_report(
            template_path=args.template,
            results_folder=args.results_folder,
            upload_files=not args.no_upload
        )
        
        print(f"\nSuccess!")
        print(f"   Experiment: {args.experiment_id}")
        print(f"   Template fields: {result['template_fields_configured']}")
        print(f"   Selected plots: {result['selected_plots']} ({result['plots_found']} found)")
        print(f"   Plot files uploaded: {result['plot_files_uploaded']}")
        print(f"   Additional files uploaded: {result['additional_files_uploaded']}")
        print(f"   Total files uploaded: {result['total_files_uploaded']}")
        print(f"   Placeholders replaced: {result['placeholders_replaced']}")
        
        return 0
        
    except Exception as e:
        import traceback
        print(f"\nERROR: {e}")
        print("Full traceback:")
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
def main():
    parser = argparse.ArgumentParser(description=f"Commit {PROCESS_NAME} to database")
    parser.add_argument("elab_id", type=int, help="eLabFTW experiment ID")
    parser.add_argument("--dry-run", action="store_true", help="Don't commit, just show what would be done")
    parser.add_argument("--init-schema-only", action="store_true", help="Only initialize process schema")
    args = parser.parse_args()

    conn = None

    try:
        conn = get_db_connection()
        cursor = conn.cursor()

        upsert_process_schema(cursor)
        print(f"✓ Process schema updated: {PROCESS_NAME} (ID: {PROCESS_ID})")

        if args.init_schema_only:
            if args.dry_run:
                print("DRY RUN - Schema initialization only; no database commit performed.")
                conn.rollback()
            else:
                conn.commit()
                print("Schema-only mode, skipping experiment data.")
            return 0

        exp_json_path = find_experiment_json(args.elab_id)
        exp_data = load_json_file(exp_json_path)

        extra_fields = exp_data.get("metadata_decoded", {}).get("extra_fields", {})
        workflow_json, lab_id = load_workflow()
        metadata = extract_metadata(extra_fields)
        raw_data = build_raw_data()
        results = build_results(args.elab_id)

        title = exp_data.get("title", "")
        user_value = (
            exp_data.get("userid_human")
            or exp_data.get("fullname")
            or exp_data.get("user")
            or ""
        )

        started_at = (
            parse_datetime(exp_data.get("started_at"))
            or parse_datetime(exp_data.get("start_time"))
            or parse_datetime(exp_data.get("created_at"))
            or parse_datetime(exp_data.get("date"))
        )

        completed_at = (
            parse_datetime(exp_data.get("completed_at"))
            or parse_datetime(exp_data.get("finish_time"))
            or parse_datetime(exp_data.get("updated_at"))
        )

        comments = exp_data.get("body") or exp_data.get("comments") or None
        status = infer_execution_status(results)

        data = {
            "title": title,
            "lab_id": lab_id,
            "status": status,
            "user": user_value,
            "started_at": started_at,
            "completed_at": completed_at,
            "workflow_json": workflow_json,
            "metadata": metadata,
            "raw_data": raw_data,
            "results": results,
            "comments": comments
        }

        if args.dry_run:
            print("DRY RUN - Would upsert process schema and experiment execution with:")
            print(json.dumps({
                "elab_id": args.elab_id,
                "experiment_json_path": str(exp_json_path),
                "payload": data
            }, indent=2, default=str))
            conn.rollback()
            return 0

        exp_db_id = upsert_experiment(cursor, args.elab_id, data)
        conn.commit()

        print(f"✓ Experiment {args.elab_id} committed successfully (DB ID: {exp_db_id})")
        return 0

    except Exception as e:
        print(f"✗ Error: {e}", file=sys.stderr)
        if conn is not None:
            try:
                conn.rollback()
            except Exception:
                pass
        return 1

    finally:
        if conn is not None:
            try:
                conn.close()
            except Exception:
                pass

if __name__ == "__main__":
    sys.exit(main())
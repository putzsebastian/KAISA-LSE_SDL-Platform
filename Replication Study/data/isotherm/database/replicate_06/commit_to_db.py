def load_analysis_results(elab_id):
    """Load analysis_results JSON produced by the analysis script if present."""
    results_folder = Path("../results")
    # preferred name used by analysis script
    preferred = results_folder / f"analysis_results_{elab_id}.json"
    if preferred.exists():
        with open(preferred, "r") as f:
            data = json.load(f)
        return data, preferred
    # fallback: any analysis_results_*.json, choose most recent
    candidates = sorted(
        results_folder.glob("analysis_results_*.json"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if candidates:
        with open(candidates[0], "r") as f:
            data = json.load(f)
        return data, candidates[0]
    return None, None


def build_results(elab_id):
    """Build results JSONB structure from files in ../results and analysis_results JSON."""
    results_folder = Path("../results")
    results_folder.mkdir(exist_ok=True, parents=True)

    analysis_data, analysis_json_path = load_analysis_results(elab_id)

    timestamp = datetime.now(timezone.utc).isoformat()

    analysis_status = None
    analysis_message = None
    warnings_list = []
    data_files = {}
    plots = {}
    summary = {
        "n_salt_conditions": None,
        "q_max_values": None,
        "K_values": None,
        "r2_values": None,
    }

    if analysis_data is not None:
        analysis_status = analysis_data.get("status")
        analysis_message = analysis_data.get("message")
        warnings_list = analysis_data.get("warnings", [])

        data_outputs = analysis_data.get("data_outputs", {})
        for key, path in data_outputs.items():
            data_files[key] = path

        if analysis_json_path is not None:
            data_files["analysis_results_json"] = str(analysis_json_path.resolve())

        plots_dict = analysis_data.get("plots", {})
        for key, path in plots_dict.items():
            plots[key] = path

        # Try to derive simple summary from langmuir_fit_parameters CSV if available
        fit_csv = data_outputs.get("langmuir_fit_parameters_csv")
        if fit_csv and Path(fit_csv).exists():
            try:
                import pandas as pd  # type: ignore

                df = pd.read_csv(fit_csv)
                if "q_max" in df.columns:
                    summary["q_max_values"] = [
                        float(v) for v in df["q_max"].dropna().tolist()
                    ]
                if "K" in df.columns:
                    summary["K_values"] = [
                        float(v) for v in df["K"].dropna().tolist()
                    ]
                if "R2" in df.columns:
                    summary["r2_values"] = [
                        float(v) for v in df["R2"].dropna().tolist()
                    ]
                summary["n_salt_conditions"] = int(len(df))
            except Exception:
                # If summary extraction fails, leave summary fields as None
                pass

    # If analysis_data was not found, still try to locate expected files by name pattern
    elab_str = str(elab_id)
    expected_data = {
        "tecan_raw_excel": results_folder / f"tecan_data_{elab_str}.xlsx",
        "processed_well_data_csv": results_folder
        / f"processed_well_data_{elab_str}.csv",
        "aggregated_isotherm_csv": results_folder
        / f"aggregated_isotherm_data_{elab_str}.csv",
        "langmuir_fit_parameters_csv": results_folder
        / f"langmuir_fit_parameters_{elab_str}.csv",
    }
    for key, path in expected_data.items():
        if key not in data_files and path.exists():
            data_files[key] = str(path.resolve())

    expected_plots = {
        "isotherms_png": results_folder / f"isotherms_{elab_str}.png",
        "isotherms_pdf": results_folder / f"isotherms_{elab_str}.pdf",
    }
    for key, path in expected_plots.items():
        if key not in plots and path.exists():
            plots[key] = str(path.resolve())

    # Default status if still None
    if analysis_status is None:
        analysis_status = "pending"

    results = {
        "analysis_status": analysis_status,
        "analysis_message": analysis_message,
        "timestamp": timestamp,
        "summary": summary,
        "data_files": data_files,
        "plots": plots,
        "warnings": warnings_list,
    }

    return results



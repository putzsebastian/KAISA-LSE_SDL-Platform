def build_results(elab_id):
    """Build results JSONB structure from analysis outputs.

    This function is generic and does not re-run analysis; it simply
    aggregates files and, if present, ingests the analysis_results JSON.
    """
    results_folder = Path("../results")
    analysis_output = load_analysis_results(elab_id)

    # Determine status
    if analysis_output and isinstance(analysis_output, dict):
        status = analysis_output.get("status", "pending")
        analysis_metadata = analysis_output.get("metadata", {})
        warnings_list = analysis_output.get("warnings", [])
        data_outputs = analysis_output.get("data_outputs", {})
        plots = analysis_output.get("plots", {})
    else:
        status = "pending"
        analysis_metadata = {}
        warnings_list = []
        data_outputs = {}
        plots = {}

    elab_str = str(elab_id)

    # Data files discovered by convention
    per_well = results_folder / f"per_well_results_{elab_str}.csv"
    if per_well.exists():
        data_outputs.setdefault("per_well_results_csv", str(per_well.resolve()))
    agg = results_folder / f"aggregated_results_{elab_str}.csv"
    if agg.exists():
        data_outputs.setdefault("aggregated_results_csv", str(agg.resolve()))
    fits = results_folder / f"langmuir_fits_{elab_str}.csv"
    if fits.exists():
        data_outputs.setdefault("langmuir_fits_csv", str(fits.resolve()))
    tecan_xlsx = results_folder / f"tecan_data_{elab_str}.xlsx"
    if tecan_xlsx.exists():
        data_outputs.setdefault("tecan_raw_data_xlsx", str(tecan_xlsx.resolve()))

    analysis_json_path = results_folder / f"analysis_results_{elab_str}.json"
    if analysis_json_path.exists():
        data_outputs.setdefault("analysis_results_json", str(analysis_json_path.resolve()))

    # Plots
    plot_png = results_folder / f"loading_isotherms_{elab_str}.png"
    if plot_png.exists():
        plots.setdefault("loading_isotherms_png", str(plot_png.resolve()))

    results = {
        "analysis_status": status,
        "analysis_timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": {
            "num_ligand_concentrations": analysis_metadata.get("num_ligand_concentrations"),
            "num_salt_concentrations": analysis_metadata.get("num_salt_concentrations"),
            "replicates": analysis_metadata.get("replicates"),
            "num_warnings": len(warnings_list),
        },
        "analysis_metadata": analysis_metadata,
        "warnings": warnings_list,
        "data_files": data_outputs,
        "plots": plots,
        "raw_analysis_output": analysis_output or {},
    }

    return results



def build_results(elab_id):
    """Build results JSONB structure from analysis outputs.

    Tries to load analysis_results_{elab_id}.json from ../results and derives
    additional structure (data_files, plots, summary, fit_results).
    """
    results_dir = Path("../results")
    analysis_json_name = f"analysis_results_{elab_id}.json"
    analysis_json_path = results_dir / analysis_json_name

    now_iso = datetime.now(timezone.utc).isoformat()

    base = {
        "analysis_status": "pending",
        "analysis_timestamp": now_iso,
        "summary": {},
        "metadata_from_analysis": {},
        "fit_results": [],
        "data_files": {},
        "plots": {},
        "warnings": [],
    }

    analysis = load_json_if_exists(analysis_json_path)
    if not analysis:
        # Even if main JSON is missing, still list whatever files exist
        files = list_folder_files(results_dir)
        base["data_files"] = {}
        base["plots"] = {}
        for fname in files:
            fpath = results_dir / fname
            if fname == analysis_json_name:
                base["data_files"]["analysis_results_json"] = str(fpath.resolve())
            elif fname == f"wells_processed_{elab_id}.csv":
                base["data_files"]["wells_processed_csv"] = str(fpath.resolve())
            elif fname == f"loading_isotherm_summary_{elab_id}.csv":
                base["data_files"]["summary_csv"] = str(fpath.resolve())
            elif fname == f"langmuir_fit_results_{elab_id}.csv":
                base["data_files"]["langmuir_fit_csv"] = str(fpath.resolve())
            elif fname == f"tecan_data_{elab_id}.xlsx":
                base["data_files"]["tecan_raw_excel"] = str(fpath.resolve())
            elif fname == f"loading_isotherms_{elab_id}.png":
                base["plots"]["loading_isotherms_png"] = str(fpath.resolve())
            elif fname == f"loading_isotherms_{elab_id}.pdf":
                base["plots"]["loading_isotherms_pdf"] = str(fpath.resolve())
        base["analysis_status"] = "pending"
        return base

    # Map top-level status
    status = analysis.get("status") or analysis.get("analysis_status")
    if status in {"success", "failed", "pending"}:
        base["analysis_status"] = status
    else:
        base["analysis_status"] = "completed" if status == "completed" else "pending"

    # Copy warnings if present
    if isinstance(analysis.get("warnings"), list):
        base["warnings"] = analysis["warnings"]

    # Copy data_outputs / plots as structured entries
    data_outputs = analysis.get("data_outputs", {}) or {}
    plots = analysis.get("plots", {}) or {}

    def abs_path_if_exists(path_str: str):
        if not path_str:
            return None
        p = Path(path_str)
        return str(p.resolve()) if p.exists() else path_str

    base["data_files"] = {
        "analysis_results_json": str(analysis_json_path.resolve()),
    }

    if "wells_processed_csv" in data_outputs:
        base["data_files"]["wells_processed_csv"] = abs_path_if_exists(
            data_outputs.get("wells_processed_csv")
        )
    if "summary_csv" in data_outputs:
        base["data_files"]["summary_csv"] = abs_path_if_exists(
            data_outputs.get("summary_csv")
        )
    if "langmuir_fit_csv" in data_outputs:
        base["data_files"]["langmuir_fit_csv"] = abs_path_if_exists(
            data_outputs.get("langmuir_fit_csv")
        )
    if "tecan_raw_excel" in data_outputs:
        base["data_files"]["tecan_raw_excel"] = abs_path_if_exists(
            data_outputs.get("tecan_raw_excel")
        )

    base["plots"] = {}
    if "loading_isotherms_png" in plots:
        base["plots"]["loading_isotherms_png"] = abs_path_if_exists(
            plots.get("loading_isotherms_png")
        )
    if "loading_isotherms_pdf" in plots:
        base["plots"]["loading_isotherms_pdf"] = abs_path_if_exists(
            plots.get("loading_isotherms_pdf")
        )

    # Metadata and summary numbers from analysis["metadata"]
    meta_block = analysis.get("metadata", {}) or {}
    base["metadata_from_analysis"] = meta_block

    summary_block = {}
    if isinstance(meta_block, dict):
        for key in ("n_ligand", "n_salt", "replicates"):
            if key in meta_block:
                summary_block[key] = meta_block.get(key)
    files_processed = analysis.get("files_processed")
    if files_processed is not None:
        summary_block["files_processed"] = files_processed
    base["summary"] = summary_block

    # Attempt to load fit_results from CSV if present
    fit_results = []
    langmuir_csv_path = None
    if "langmuir_fit_csv" in data_outputs:
        langmuir_csv_path = Path(data_outputs.get("langmuir_fit_csv"))
    else:
        candidate = results_dir / f"langmuir_fit_results_{elab_id}.csv"
        if candidate.exists():
            langmuir_csv_path = candidate

    if langmuir_csv_path and langmuir_csv_path.exists():
        try:
            import csv

            with open(langmuir_csv_path, newline="") as csvfile:
                reader = csv.DictReader(csvfile)
                for row in reader:
                    fit_results.append(row)
        except Exception:
            fit_results = []

    base["fit_results"] = fit_results

    # Ensure we record actual time of aggregation
    base["analysis_timestamp"] = now_iso

    return base



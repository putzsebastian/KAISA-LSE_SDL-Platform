def build_results(elab_id: int) -> dict:
    """Build results JSONB structure from analysis outputs.

    Expects the analysis script to have written analysis_results_{elab_id}.json
    and associated CSV/plot files into ../results/.
    """
    results_folder = Path("../results")
    results: dict = {
        "analysis_status": "pending",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "analysis_results": None,
        "summary": {},
        "data_files": {},
        "plots": {},
    }

    if not results_folder.exists():
        return results

    # Load primary analysis_results JSON if present
    analysis_json_name = f"analysis_results_{elab_id}.json"
    analysis_json_path = results_folder / analysis_json_name
    if analysis_json_path.exists():
        try:
            with open(analysis_json_path, "r") as f:
                analysis = json.load(f)
            results["analysis_results"] = analysis
            status = analysis.get("status", "failed")
            results["analysis_status"] = "completed" if status == "success" else "failed"
        except Exception:
            results["analysis_status"] = "failed"
    else:
        # No dedicated analysis JSON found; just report files
        results["analysis_status"] = "pending"

    # Data files from known naming patterns
    data_files: dict = {}
    tecan_raw = results_folder / f"tecan_data_{elab_id}.xlsx"
    if tecan_raw.exists():
        data_files["tecan_raw_file"] = str(tecan_raw.resolve())
    per_well = results_folder / f"tecan_loading_isotherm_per_well_{elab_id}.csv"
    if per_well.exists():
        data_files["per_well_csv"] = str(per_well.resolve())
    aggregated = results_folder / f"tecan_loading_isotherm_aggregated_{elab_id}.csv"
    if aggregated.exists():
        data_files["aggregated_csv"] = str(aggregated.resolve())
    if analysis_json_path.exists():
        data_files["analysis_results_json"] = str(analysis_json_path.resolve())

    results["data_files"] = data_files

    # Plot files
    plots: dict = {}
    png = results_folder / f"loading_isotherms_{elab_id}.png"
    if png.exists():
        plots["isotherms_png"] = str(png.resolve())
    pdf = results_folder / f"loading_isotherms_{elab_id}.pdf"
    if pdf.exists():
        plots["isotherms_pdf"] = str(pdf.resolve())

    # If analysis_results JSON exists, prefer plot/file paths stored there as well
    if results.get("analysis_results"):
        ar = results["analysis_results"]
        ar_plots = ar.get("plots", {}) if isinstance(ar, dict) else {}
        ar_data_outputs = ar.get("data_outputs", {}) if isinstance(ar, dict) else {}
        # Merge, giving precedence to explicit keys above
        for k, v in ar_plots.items():
            plots.setdefault(k, v)
        for k, v in ar_data_outputs.items():
            data_files.setdefault(k, v)

    results["plots"] = plots

    # Build simple numeric summary from fit_results if present
    summary: dict = {}
    ar = results.get("analysis_results") or {}
    if isinstance(ar, dict):
        fit_results = ar.get("fit_results")
        metadata = ar.get("metadata", {})
        if isinstance(metadata, dict):
            num_lig = metadata.get("num_ligand_concentrations") or metadata.get("num_ligand_conc")
            if isinstance(num_lig, (int, float)):
                summary["num_ligand_conditions"] = int(num_lig)
        if isinstance(fit_results, list) and fit_results:
            import math

            q_max_vals = []
            K_vals = []
            r2_vals = []
            for fr in fit_results:
                if not isinstance(fr, dict):
                    continue
                q_max = fr.get("q_max")
                K = fr.get("K")
                r2 = fr.get("R2")
                if isinstance(q_max, (int, float)) and isinstance(K, (int, float)) and isinstance(r2, (int, float)):
                    q_max_vals.append(float(q_max))
                    K_vals.append(float(K))
                    r2_vals.append(float(r2))
            num_success = len(q_max_vals)
            num_total = len(fit_results)
            summary["num_salt_conditions"] = num_total
            summary["num_fit_success"] = num_success
            summary["num_fit_failed"] = max(0, num_total - num_success)

            def _mean_std(values: list[float]) -> tuple[float | None, float | None]:
                if not values:
                    return None, None
                m = sum(values) / len(values)
                if len(values) > 1:
                    var = sum((x - m) ** 2 for x in values) / (len(values) - 1)
                    s = math.sqrt(var)
                else:
                    s = 0.0
                return m, s

            q_mean, q_std = _mean_std(q_max_vals)
            k_mean, k_std = _mean_std(K_vals)
            r2_mean, r2_std = _mean_std(r2_vals)
            if q_mean is not None:
                summary["q_max_mean"] = q_mean
                summary["q_max_std"] = q_std
            if k_mean is not None:
                summary["K_mean"] = k_mean
                summary["K_std"] = k_std
            if r2_mean is not None:
                summary["r2_mean"] = r2_mean
                summary["r2_std"] = r2_std

    results["summary"] = summary

    return results



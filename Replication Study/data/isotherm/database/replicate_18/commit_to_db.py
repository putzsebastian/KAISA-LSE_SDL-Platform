def extract_metadata(extra_fields: dict) -> dict:
    """Extract and map metadata from eLabFTW extra fields.

    This function respects field types and possible list encodings.
    """
    metadata: dict = {}
    for elab_name, db_name in FIELD_MAPPING.items():
        if elab_name not in extra_fields:
            continue
        field = extra_fields[elab_name]
        if not isinstance(field, dict):
            continue
        value = field.get("value")
        field_type = field.get("type")  # e.g. 'number', 'text'
        parsed = parse_field(value, field_type=field_type)
        # Cast to int for some known integer fields where parse_field returns numeric
        if db_name in {"replicates", "num_salt_concentrations", "num_ligand_concentrations"} and isinstance(
            parsed, (int, float)
        ):
            try:
                parsed = int(parsed)
            except Exception:
                pass
        metadata[db_name] = parsed
    return metadata



def parse_numeric(value):
    """Extract a numeric value from a string like '25 °C' or '100 mM'.

    Call this ONLY for a single-valued field eLabFTW types as a number. On a text field
    it is destructive - '20 mM NaAc' becomes 20.0 and the buffer identity is gone - and
    on a delimited list it keeps only the first element. When in doubt, store the
    original string unchanged.
    """
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        text = value.strip()
        import re

        # If the whole string looks like a single number (allowing comma decimal)
        m_full = re.fullmatch(r"[-+]?\d{1,3}(?:[.,]\d+)?", text)
        if m_full:
            return float(text.replace(",", "."))
        # Otherwise, extract first float-like substring
        match = re.search(r"[-+]?\d*\.?,?\d+", text)
        if match:
            num_str = match.group(0).replace(",", ".")
            try:
                return float(num_str)
            except ValueError:
                return None
    return None


def parse_field(value, field_type=None):
    """Route an eLabFTW value by what it IS, not by which parameter it came from.

    Any field may arrive as a delimited list, so the delimiter check comes first.
    """
    if value is None or value == "":
        return None
    if isinstance(value, (list, int, float)):
        return value
    text = str(value).strip()
    # a list if a delimiter separates more than one token; "1,5" (decimal comma) is one
    for sep in (";", ","):
        parts = [p.strip() for p in text.split(sep) if p.strip()]
        if len(parts) > 1:
            # Check if this is actually a decimal comma case (single numeric token)
            if sep == "," and len(parts) == 2:
                joined = "".join(parts)
                try:
                    return float(joined)
                except ValueError:
                    pass
            # Try to parse all parts as floats
            try:
                return [float(p.replace(",", ".")) for p in parts]
            except ValueError:
                return parts
    if field_type == "number":
        num = parse_numeric(text)
        return num if num is not None else text
    return text



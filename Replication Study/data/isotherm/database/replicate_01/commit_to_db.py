def build_results(elab_id):
    """Build results JSONB structure from analysis outputs."""
    now = datetime.now(timezone.utc).isoformat()
    analysis = _load_analysis_results(elab_id)
    if not analysis:
        return {
            "analysis_status": "pending",
            "analysis_message": "Analysis JSON not found",
            "timestamp": now,
            "summary": {
                "files_processed": 0,
                "n_salt_concentrations": None,
                "n_ligand_concentrations": None,
                "n_langmuir_fits": None,
            },
            "analysis_metadata": {},
            "langmuir_fits": [],
            "data_files": {},
            "plots": {},
            "warnings": [],
        }

    status = analysis.get("status", "failed")
    message = analysis.get("message", "")
    metadata = analysis.get("metadata", {}) or {}
    files_processed = int(analysis.get("files_processed", 0) or 0)
    warnings_list = analysis.get("warnings", []) or []

    ligand_concs = metadata.get("ligand_concs") or []
    salt_concs = metadata.get("salt_concs") or []

    n_ligand = len(ligand_concs) if isinstance(ligand_concs, list) else None
    n_salt = len(salt_concs) if isinstance(salt_concs, list) else None

    data_outputs = analysis.get("data_outputs", {}) or {}
    plots_in = analysis.get("plots", {}) or {}

    # Map data files to just their basenames
    results_json_name = f"analysis_results_{elab_id}.json"
    data_files = {"analysis_results_json": results_json_name}
    if "tecan_raw_excel" in data_outputs:
        data_files["tecan_raw_excel"] = Path(
            data_outputs["tecan_raw_excel"]
        ).name
    if "per_well_data_csv" in data_outputs:
        data_files["per_well_data_csv"] = Path(
            data_outputs["per_well_data_csv"]
        ).name
    if "aggregated_data_csv" in data_outputs:
        data_files["aggregated_data_csv"] = Path(
            data_outputs["aggregated_data_csv"]
        ).name
    if "langmuir_fits_csv" in data_outputs:
        data_files["langmuir_fits_csv"] = Path(
            data_outputs["langmuir_fits_csv"]
        ).name

    # Map plots to basenames
    plots = {}
    png = plots_in.get("isotherms_png")
    pdf = plots_in.get("isotherms_pdf")
    if png:
        plots["loading_isotherms_png"] = Path(png).name
    if pdf:
        plots["loading_isotherms_pdf"] = Path(pdf).name

    # Try to read Langmuir fits CSV into structured list
    langmuir_fits_list = []
    fits_csv_name = data_files.get("langmuir_fits_csv")
    if fits_csv_name:
        try:
            import csv

            csv_path = Path("../results") / fits_csv_name
            if csv_path.exists():
                with open(csv_path, newline="") as f:
                    reader = csv.DictReader(f)
                    for row in reader:
                        try:
                            langmuir_fits_list.append(
                                {
                                    "salt": float(row.get("salt"))
                                    if row.get("salt") not in (None, "")
                                    else None,
                                    "q_max": float(row.get("q_max"))
                                    if row.get("q_max") not in (None, "")
                                    else None,
                                    "K": float(row.get("K"))
                                    if row.get("K") not in (None, "")
                                    else None,
                                    "R2": float(row.get("R2"))
                                    if row.get("R2") not in (None, "")
                                    else None,
                                }
                            )
                        except Exception:
                            continue
        except Exception:
            langmuir_fits_list = []

    results_obj = {
        "analysis_status": status,
        "analysis_message": message,
        "timestamp": now,
        "summary": {
            "files_processed": files_processed,
            "n_salt_concentrations": n_salt,
            "n_ligand_concentrations": n_ligand,
            "n_langmuir_fits": len(langmuir_fits_list)
            if langmuir_fits_list
            else None,
        },
        "analysis_metadata": metadata,
        "langmuir_fits": langmuir_fits_list,
        "data_files": data_files,
        "plots": plots,
        "warnings": warnings_list,
    }
    return results_obj



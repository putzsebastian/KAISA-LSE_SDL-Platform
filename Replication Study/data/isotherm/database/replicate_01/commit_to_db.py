def parse_numeric(value):
    """Extract a numeric value from a string like '25 °C' or '100 mM'.

    Call this ONLY for a single-valued field eLabFTW types as a number.
    """
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip()
    if text == "":
        return None
    # normalise decimal comma
    text = text.replace(",", ".")
    import re

    match = re.search(r"[-+]?[0-9]*\.?[0-9]+", text)
    if not match:
        return None
    try:
        return float(match.group(0))
    except ValueError:
        return None


def parse_field(value, field_type=None):
    """Route an eLabFTW value by what it IS, not by which parameter it came from.

    Any field may arrive as a delimited list, so the delimiter check comes first.
    """
    if value is None or value == "":
        return None
    if isinstance(value, (list, int, float)):
        return value
    text = str(value).strip()
    # check for list with ';' or ',' as delimiter
    for sep in (";", ","):
        parts = [p.strip() for p in text.split(sep) if p.strip()]
        if len(parts) > 1:
            # try to convert all to float; if any fail, keep as strings
            try:
                return [float(p.replace(",", ".")) for p in parts]
            except ValueError:
                return parts
    # single value
    if field_type == "number":
        num = parse_numeric(text)
        if num is not None:
            return num
    return text



def extract_metadata(extra_fields):
    """Extract and map metadata from eLabFTW extra fields.

    Applies FIELD_MAPPING and respects field types and potential list values.
    """
    metadata = {}
    for elab_name, db_name in FIELD_MAPPING.items():
        if elab_name not in extra_fields:
            continue
        field = extra_fields[elab_name]
        value = field.get("value")
        field_type = field.get("type")
        parsed = parse_field(value, field_type=field_type)
        metadata[db_name] = parsed
    return metadata



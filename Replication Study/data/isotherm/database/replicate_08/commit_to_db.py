def build_results(elab_id):
    """Build results JSONB structure by inspecting ../results and ../analysis.

    This function is generic but tailored to the outputs of the provided analysis
    script (loading isotherm evaluation).
    """

    results = {
        "analysis_status": "pending",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": {},
        "langmuir_fits": [],
        "data_files": {},
        "plots": {},
        "warnings": [],
        "raw_analysis": {},
    }

    # Load analysis JSON if available
    analysis_json, analysis_path = load_analysis_results(elab_id)
    if analysis_json is not None:
        status = analysis_json.get("status", "pending")
        results["analysis_status"] = status
        results["raw_analysis"] = analysis_json
        if analysis_path:
            results["data_files"]["analysis_results_json"] = analysis_path

        # Summary fields
        meta = analysis_json.get("metadata", {}) or {}
        results["summary"]["files_processed"] = int(
            analysis_json.get("files_processed", 0) or 0
        )
        if "n_ligand" in meta:
            try:
                results["summary"]["n_ligand"] = int(meta.get("n_ligand"))
            except Exception:
                pass
        if "n_salt" in meta:
            try:
                results["summary"]["n_salt"] = int(meta.get("n_salt"))
            except Exception:
                pass
        if "n_replicates" in meta:
            try:
                results["summary"]["n_replicates"] = int(meta.get("n_replicates"))
            except Exception:
                pass

        # Warnings
        if isinstance(analysis_json.get("warnings"), list):
            results["warnings"] = analysis_json.get("warnings", [])

        # Data outputs and plots from analysis JSON
        data_outputs = analysis_json.get("data_outputs", {}) or {}
        plots = analysis_json.get("plots", {}) or {}

        for key, path in data_outputs.items():
            results["data_files"][key] = path
        for key, path in plots.items():
            results["plots"][key] = path

        # Try to load Langmuir fits CSV into a simplified structure if present
        langmuir_csv = data_outputs.get("langmuir_fits_csv")
        if langmuir_csv and Path(langmuir_csv).exists():
            try:
                import csv

                with open(langmuir_csv, newline="") as f:
                    reader = csv.DictReader(f)
                    for row in reader:
                        try:
                            results["langmuir_fits"].append(
                                {
                                    "salt_index": int(row.get("salt_index"))
                                    if row.get("salt_index") not in (None, "")
                                    else None,
                                    "salt_concentration": float(row.get("salt_concentration"))
                                    if row.get("salt_concentration") not in (None, "")
                                    else None,
                                    "q_max": float(row.get("q_max"))
                                    if row.get("q_max") not in (None, "")
                                    else None,
                                    "K": float(row.get("K"))
                                    if row.get("K") not in (None, "")
                                    else None,
                                    "R2": float(row.get("R2"))
                                    if row.get("R2") not in (None, "")
                                    else None,
                                }
                            )
                        except Exception:
                            continue
            except Exception:
                # If reading CSV fails, just omit structured langmuir_fits; raw CSV path is kept
                pass

        results["summary"]["n_langmuir_fits"] = len(results["langmuir_fits"])

    # Also scan results/ and analysis/ directories to list files (best-effort)
    results_folder = Path("../results")
    analysis_folder = Path("../analysis")

    if results_folder.exists():
        for f in results_folder.iterdir():
            if not f.is_file():
                continue
            name = f.name
            if name.endswith(".png") and "loading_isotherms" in name:
                results["plots"].setdefault("loading_isotherms_png", str(f.resolve()))
            elif name.endswith(f"wells_processed_{elab_id}.csv"):
                results["data_files"].setdefault("wells_processed_csv", str(f.resolve()))
            elif name.endswith(f"aggregated_isotherm_{elab_id}.csv"):
                results["data_files"].setdefault(
                    "aggregated_isotherm_csv", str(f.resolve())
                )
            elif name.endswith(f"langmuir_fits_{elab_id}.csv"):
                results["data_files"].setdefault("langmuir_fits_csv", str(f.resolve()))
            elif name.endswith(f"analysis_results_{elab_id}.json"):
                results["data_files"].setdefault("analysis_results_json", str(f.resolve()))
            elif name.endswith(f"tecan_data_{elab_id}.xlsx"):
                results["data_files"].setdefault("tecan_raw_excel", str(f.resolve()))

    if analysis_folder.exists():
        for f in analysis_folder.iterdir():
            if f.is_file():
                results.setdefault("additional_files", []).append(str(f.resolve()))

    return results



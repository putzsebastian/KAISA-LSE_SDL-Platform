def build_results(elab_id):
    """Build results JSONB structure from analysis outputs and file listings."""
    results_folder = Path("../results")
    analysis_folder = Path("../analysis")

    results = {
        "analysis_status": "pending",
        "analysis_timestamp": datetime.now(timezone.utc).isoformat(),
        "analysis_message": "",
        "warnings": [],
        "summary": {},
        "fit_results": [],
        "metadata": {},
        "data_files": {},
        "plots": {},
    }

    analysis_data, analysis_path = load_analysis_results(elab_id)

    if analysis_data is not None:
        status = analysis_data.get("status", "pending")
        results["analysis_status"] = status
        results["analysis_message"] = analysis_data.get("message", "")
        results["warnings"] = analysis_data.get("warnings", [])

        meta = analysis_data.get("metadata", {})
        results["metadata"] = meta

        fit_results = analysis_data.get("fit_results")
        if isinstance(fit_results, list):
            results["fit_results"] = fit_results

        # Build summary metrics
        try:
            n_ligand = (
                int(meta.get("n_ligand"))
                if meta.get("n_ligand") is not None
                else None
            )
        except (TypeError, ValueError):
            n_ligand = None
        try:
            n_salt = (
                int(meta.get("n_salt")) if meta.get("n_salt") is not None else None
            )
        except (TypeError, ValueError):
            n_salt = None
        try:
            n_repl = (
                int(meta.get("n_replicates"))
                if meta.get("n_replicates") is not None
                else None
            )
        except (TypeError, ValueError):
            n_repl = None

        ligand_concs = meta.get("ligand_concentrations") or []
        try:
            max_c0 = max(ligand_concs) if ligand_concs else None
        except Exception:
            max_c0 = None

        q_max_vals = [
            fr.get("q_max")
            for fr in (fit_results or [])
            if fr.get("q_max") is not None
        ]
        K_vals = [
            fr.get("K") for fr in (fit_results or []) if fr.get("K") is not None
        ]
        R2_vals = [
            fr.get("R2") for fr in (fit_results or []) if fr.get("R2") is not None
        ]

        def safe_mean(vals):
            nums = []
            for v in vals:
                try:
                    nums.append(float(v))
                except (TypeError, ValueError):
                    continue
            return sum(nums) / len(nums) if nums else None

        results["summary"] = {
            "n_ligand": n_ligand,
            "n_salt": n_salt,
            "n_replicates": n_repl,
            "max_initial_ligand_concentration": max_c0,
            "num_fit_results": len(fit_results) if fit_results is not None else 0,
            "mean_q_max": safe_mean(q_max_vals),
            "mean_K": safe_mean(K_vals),
            "mean_R2": safe_mean(R2_vals),
        }

        # Data files from analysis JSON
        data_outputs = analysis_data.get("data_outputs", {})
        data_files = {}
        if analysis_path is not None:
            data_files["analysis_results_json"] = str(analysis_path.resolve())
        if "wells_processed_csv" in data_outputs:
            data_files["wells_processed_csv"] = data_outputs.get(
                "wells_processed_csv"
            )
        if "aggregated_isotherm_csv" in data_outputs:
            data_files["aggregated_isotherm_csv"] = data_outputs.get(
                "aggregated_isotherm_csv"
            )
        if "tecan_raw_excel" in data_outputs:
            data_files["tecan_raw_excel"] = data_outputs.get("tecan_raw_excel")
        results["data_files"] = data_files

        # Plots
        plots = analysis_data.get("plots", {})
        if "isotherms_png" in plots:
            results["plots"]["isotherms_png"] = plots.get("isotherms_png")
    else:
        # No analysis JSON; still list files
        results["analysis_status"] = "pending"
        results["analysis_message"] = (
            "Analysis JSON not found; only file listings stored."
        )

    # Also record generic listings of results/analysis folders
    results["all_result_files"] = list_folder_files(results_folder)
    if analysis_folder.exists():
        results["analysis_folder_files"] = list_folder_files(analysis_folder)

    return results



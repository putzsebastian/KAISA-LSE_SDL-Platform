def build_results(elab_id):
    """Build results JSONB structure from analysis outputs.

    Looks for analysis_results_{elab_id}.json in ../results. If present, parses it
    and extracts status, warnings, metadata summary, and file paths. If not present,
    returns a minimal failed status.
    """
    results_folder = Path("../results")
    analysis_json_path = results_folder / f"analysis_results_{elab_id}.json"

    timestamp = datetime.now(timezone.utc).isoformat()

    if not analysis_json_path.exists():
        return {
            "analysis_status": "failed",
            "timestamp": timestamp,
            "summary": {
                "message": "analysis_results JSON not found; analysis may not have been run",
                "warnings": [],
            },
            "data_files": {},
            "plots": {},
        }

    try:
        with open(analysis_json_path, "r") as f:
            analysis = json.load(f)
    except Exception as e:
        return {
            "analysis_status": "failed",
            "timestamp": timestamp,
            "summary": {
                "message": f"Failed to parse analysis_results JSON: {e}",
                "warnings": [],
            },
            "data_files": {
                "analysis_results_json": str(analysis_json_path.resolve()),
            },
            "plots": {},
        }

    status_raw = analysis.get("status", "failed")
    if status_raw == "success":
        analysis_status = "completed"
    elif status_raw == "failed":
        analysis_status = "failed"
    else:
        analysis_status = "pending"

    md = analysis.get("metadata", {}) or {}
    files = analysis.get("data_outputs", {}) or {}
    plots = analysis.get("plots", {}) or {}
    warnings_list = analysis.get("warnings", []) or []
    message = analysis.get("message", "")

    # Derive simple summary metrics if present
    n_ligand = md.get("n_ligand")
    n_salt = md.get("n_salt")
    replicates = md.get("replicates")
    fit_results = md.get("langmuir_fit_results") or []

    # Try to infer number of used wells and groups from summary CSV, if present
    n_plate_wells = 96
    n_used_wells = None
    n_valid_groups = None

    summary_csv = files.get("loading_isotherm_summary") or files.get(
        "loading_isotherm_summary_csv"
    )
    if summary_csv:
        try:
            import pandas as pd  # type: ignore

            df = pd.read_csv(summary_csv)
            n_valid_groups = int(len(df))
            # each group corresponds to replicates wells
            if replicates:
                n_used_wells = int(len(df) * int(replicates))
        except Exception:
            pass

    summary = {
        "n_ligand": n_ligand,
        "n_salt": n_salt,
        "replicates": replicates,
        "n_plate_wells": n_plate_wells,
        "n_used_wells": n_used_wells,
        "n_valid_groups": n_valid_groups,
        "fit_results": fit_results,
        "warnings": warnings_list,
        "message": message,
    }

    data_files = {
        "analysis_results_json": str(analysis_json_path.resolve()),
    }
    # Normalize known keys from analysis script
    if "raw_plate_with_mapping" in files:
        data_files["raw_plate_with_mapping_csv"] = files["raw_plate_with_mapping"]
    if "loading_isotherm_summary" in files:
        data_files["loading_isotherm_summary_csv"] = files["loading_isotherm_summary"]
    if "langmuir_fit_results_csv" in files:
        data_files["langmuir_fit_results_csv"] = files["langmuir_fit_results_csv"]
    if "tecan_data" in files:
        data_files["tecan_data_excel"] = files["tecan_data"]

    plots_out = {}
    if "loading_isotherms_png" in plots:
        plots_out["loading_isotherms_png"] = plots["loading_isotherms_png"]

    return {
        "analysis_status": analysis_status,
        "timestamp": timestamp,
        "summary": summary,
        "data_files": data_files,
        "plots": plots_out,
    }



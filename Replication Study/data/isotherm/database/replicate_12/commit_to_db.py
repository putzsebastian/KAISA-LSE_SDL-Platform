def extract_metadata(extra_fields):
    """Extract and map metadata from eLabFTW extra fields.

    This respects eLabFTW field types to decide when to parse numeric values and
    also handles delimited lists generically.
    """
    metadata = {}
    for elab_name, db_name in FIELD_MAPPING.items():
        if elab_name not in extra_fields:
            continue
        field = extra_fields[elab_name]
        if not isinstance(field, dict):
            continue
        value = field.get("value")
        field_type = field.get("type")
        parsed_value = parse_field(value, field_type=field_type)
        metadata[db_name] = parsed_value
    return metadata


def list_folder_files(folder_path):
    """List files in a folder."""
    folder = Path(folder_path)
    if folder.exists():
        return [f.name for f in folder.iterdir() if f.is_file()]
    return []



def build_results(elab_id):
    """Build results JSONB structure from analysis outputs.

    This function inspects the ../results folder, attempts to load the
    analysis_results_<id>.json created by the analysis script, and
    extracts key metrics and file/plot paths.
    """
    results_folder = Path("../results")
    results_folder_resolved = results_folder.resolve()

    analysis_data, analysis_path = load_analysis_results(elab_id)

    analysis_status = None
    message = None
    warnings_list = None
    summary = {
        "num_ligand_concentrations": None,
        "num_salt_concentrations": None,
        "replicates": None,
        "n_wells_processed": None,
        "n_conditions": None,
    }

    data_files = {}
    plots = {}

    if analysis_data is not None:
        analysis_status = analysis_data.get("status")
        message = analysis_data.get("message")
        warnings_list = analysis_data.get("warnings")

        # Map known data outputs
        data_outputs = analysis_data.get("data_outputs", {})
        if isinstance(data_outputs, dict):
            for key, path in data_outputs.items():
                if isinstance(path, str):
                    data_files[key] = path

        # Add the analysis_results JSON itself
        data_files.setdefault("analysis_results_json", str(analysis_path.resolve()))

        # Plots
        plots_dict = analysis_data.get("plots", {})
        if isinstance(plots_dict, dict):
            for key, path in plots_dict.items():
                if isinstance(path, str):
                    plots[key] = path

        # Summary metrics from analysis metadata and data
        meta = analysis_data.get("metadata", {}) or {}
        if isinstance(meta, dict):
            summary["num_ligand_concentrations"] = meta.get("num_ligand_concentrations")
            summary["num_salt_concentrations"] = meta.get("num_salt_concentrations")
            summary["replicates"] = meta.get("replicates")

        summary["n_wells_processed"] = analysis_data.get("files_processed")

        # Estimate number of conditions from langmuir fit results CSV if present
        langmuir_key = "langmuir_fit_results_csv"
        langmuir_path = data_outputs.get(langmuir_key) if isinstance(data_outputs, dict) else None
        if isinstance(langmuir_path, str):
            try:
                import pandas as pd  # local import to avoid mandatory dependency when not needed
                df = pd.read_csv(langmuir_path)
                summary["n_conditions"] = int(df.shape[0])
            except Exception:
                summary["n_conditions"] = None
    else:
        # No analysis JSON found; fall back to listing files
        analysis_status = "failed"
        message = f"analysis_results_{elab_id}.json not found in results folder."

    # Also include generic listing of results and analysis folders
    all_results_files = list_folder_files(results_folder_resolved)
    analysis_folder = Path("../analysis").resolve()
    analysis_files = list_folder_files(analysis_folder)

    result_obj = {
        "analysis_status": analysis_status,
        "message": message,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": summary,
        "data_files": data_files,
        "plots": plots,
        "warnings": warnings_list if isinstance(warnings_list, list) else [],
        "raw_analysis": analysis_data if isinstance(analysis_data, dict) else None,
        "result_folder_listing": {
            "results_folder": str(results_folder_resolved),
            "results_files": all_results_files,
            "analysis_folder": str(analysis_folder),
            "analysis_files": analysis_files,
        },
    }

    return result_obj



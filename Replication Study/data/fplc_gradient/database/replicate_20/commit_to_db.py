def build_results(elab_id):
    """Build results JSONB structure from files in ../results and ../analysis.

    Integrates outputs from the AKTA analysis script when available.
    """
    results_folder = Path("../results")
    analysis_folder = Path("../analysis")

    data_files = {}
    plots = {}

    # Load structured analysis_results JSON if it exists
    analysis_payload = _load_analysis_results(elab_id)

    # Infer status and message from analysis payload if available
    if analysis_payload is not None:
        analysis_status = analysis_payload.get("status", "success")
        message = analysis_payload.get("message", "")
    else:
        analysis_status = "pending"
        message = "AKTA analysis results JSON not found; analysis may not have been run yet."

    # Expected main files
    results_json_name = f"analysis_results_{elab_id}.json"
    processed_csv_name = f"akta_processed_{elab_id}.csv"
    peaks_csv_name = f"akta_peaks_{elab_id}.csv"
    chrom_png_name = f"chromatogram_{elab_id}.png"
    chrom_pdf_name = f"chromatogram_{elab_id}.pdf"

    if (results_folder / results_json_name).exists():
        data_files["analysis_results_json"] = results_json_name
    if (results_folder / processed_csv_name).exists():
        data_files["processed_akta_csv"] = processed_csv_name
    if (results_folder / peaks_csv_name).exists():
        data_files["peaks_csv"] = peaks_csv_name

    if (results_folder / chrom_png_name).exists():
        plots["chromatogram_png"] = chrom_png_name
    if (results_folder / chrom_pdf_name).exists():
        plots["chromatogram_pdf"] = chrom_pdf_name

    # Derive summary from analysis payload if available
    summary = {}
    if analysis_payload is not None:
        peaks = (
            analysis_payload.get("metadata", {})
            .get("peaks")
            or analysis_payload.get("metadata", {}).get("peaks_summary")
            or []
        )
        if isinstance(peaks, list) and peaks:
            retention_times = []
            heights = []
            for p in peaks:
                if not isinstance(p, dict):
                    continue
                rt = p.get("retention_time_min") or p.get("time_min")
                h = p.get("height_mAU") or p.get("height")
                if rt is not None:
                    try:
                        retention_times.append(float(rt))
                    except (TypeError, ValueError):
                        pass
                if h is not None:
                    try:
                        heights.append(float(h))
                    except (TypeError, ValueError):
                        pass
            summary["n_peaks"] = len(peaks)
            if retention_times:
                summary["retention_times_min"] = retention_times
            if heights:
                summary["peak_heights_mau"] = heights

    result_obj = {
        "analysis_status": analysis_status,
        "analysis_timestamp": datetime.now(timezone.utc).isoformat(),
        "message": message,
        "summary": summary,
        "data_files": data_files,
        "plots": plots,
        "raw_analysis": analysis_payload,
    }

    return result_obj



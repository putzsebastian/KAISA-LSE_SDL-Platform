def build_results(elab_id):
    """Build results JSONB structure.

    Integrates outputs from the AKTA analysis script when available and
    also records generic file listings.
    """

    now = datetime.now(timezone.utc).isoformat()

    results_root = Path("../results")
    analysis_root = Path("../analysis")

    analysis_data = load_analysis_results(elab_id)

    if analysis_data is None:
        analysis_status = "failed"
        analysis_message = "AKTA analysis_results JSON not found."
        num_points = None
        num_peaks = None
        peaks = []
        processed_csv = None
        chrom_png = None
        chrom_pdf = None
    else:
        status_raw = analysis_data.get("status", "failed")
        if status_raw == "success":
            analysis_status = "completed"
        else:
            analysis_status = "failed"

        analysis_message = analysis_data.get("message", "")
        num_points = int(analysis_data.get("files_processed") or 0)

        meta = analysis_data.get("metadata", {}) or {}
        num_peaks = int(meta.get("num_peaks_detected") or 0)
        peaks = meta.get("peaks") or []

        data_outputs = analysis_data.get("data_outputs", {}) or {}
        processed_csv = data_outputs.get("processed_chromatogram_csv")

        plots_info = analysis_data.get("plots", {}) or {}
        chrom_png = plots_info.get("png")
        chrom_pdf = plots_info.get("pdf")

    data_files = {}
    if processed_csv:
        data_files["processed_chromatogram_csv"] = processed_csv
    analysis_results_file = results_root / f"analysis_results_{elab_id}.json"
    if analysis_results_file.exists():
        data_files["analysis_results_json"] = str(analysis_results_file.resolve())

    plots = {}
    if chrom_png:
        plots["chromatogram_png"] = chrom_png
    else:
        plots["chromatogram_png"] = str((results_root / f"chromatogram_{elab_id}.png").resolve())
    if chrom_pdf:
        plots["chromatogram_pdf"] = chrom_pdf
    else:
        plots["chromatogram_pdf"] = str((results_root / f"chromatogram_{elab_id}.pdf").resolve())

    files_listing = {
        "results_folder": list_folder_files(results_root),
        "analysis_folder": list_folder_files(analysis_root),
    }

    results = {
        "analysis_status": analysis_status,
        "analysis_message": analysis_message,
        "analysis_timestamp": now,
        "summary": {
            "num_points": num_points,
            "num_peaks_detected": num_peaks,
        },
        "peaks": peaks,
        "data_files": data_files,
        "plots": plots,
        "files": files_listing,
    }

    return results



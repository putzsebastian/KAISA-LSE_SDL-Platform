def extract_metadata(extra_fields):
    """Extract and map metadata from eLabFTW extra fields.

    Uses FIELD_MAPPING and preserves types according to eLab field definitions.
    Numeric parsing is only attempted for fields whose eLab type is 'number'.
    Lists are detected via parse_field and stored as arrays when applicable.
    """

    metadata = {}
    for elab_name, db_name in FIELD_MAPPING.items():
        if elab_name not in extra_fields:
            continue
        field = extra_fields[elab_name]
        if isinstance(field, dict):
            value = field.get("value")
            field_type = field.get("type")  # e.g. 'number', 'text'
        else:
            value = None
            field_type = None

        parsed = parse_field(value, field_type=field_type)

        # Special case: linked_process_id must remain string as per user note
        if db_name == "linked_process_id" and parsed is not None:
            metadata[db_name] = str(parsed)
        else:
            metadata[db_name] = parsed

    return metadata



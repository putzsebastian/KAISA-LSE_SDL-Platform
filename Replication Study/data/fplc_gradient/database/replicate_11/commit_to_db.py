def parse_numeric(value: str):
    """Extract a numeric value from a string like '25 °C' or '100 mM'.

    Call this ONLY after determining that the field is numeric and single-valued.
    Returns float or None if no numeric content is found.
    """
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip()
    if text == "":
        return None
    import re
    # Allow decimal commas by replacing with dot before parsing
    match = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", text.replace(",", "."))
    if match:
        try:
            return float(match.group())
        except ValueError:
            return None
    return None


def parse_field(value, field_type: str | None = None):
    """Parse an eLabFTW field value.

    Any field may arrive as a delimited list. Detect lists first; if the
    value is single-valued and the field_type is 'number', coerce to float.
    Otherwise, return the string as-is.
    """
    if value is None or value == "":
        return None
    if isinstance(value, (list, int, float)):
        return value
    text = str(value).strip()

    # Detect list values using ';' or ',' as delimiters, but avoid treating
    # a decimal comma (e.g. '1,5') as a list.
    for sep in (';', ','):
        parts = [p.strip() for p in text.split(sep) if p.strip()]
        if len(parts) > 1:
            # If this looks like a decimal comma case (e.g. "1,5"), do not split
            if sep == ',' and len(parts) == 2:
                joined = ''.join(parts)
                # If joined string is numeric (possibly with one decimal), treat as single
                if parse_numeric(joined) is not None:
                    break
            # Try to parse all parts as floats; if any fail, keep as strings
            numeric_parts = []
            all_numeric = True
            for p in parts:
                num = parse_numeric(p)
                if num is None:
                    all_numeric = False
                    break
                numeric_parts.append(num)
            return numeric_parts if all_numeric else parts

    if field_type == 'number':
        num = parse_numeric(text)
        return num if num is not None else text
    return text



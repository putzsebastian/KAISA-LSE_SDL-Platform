def build_results(elab_id):
    """Build results JSONB structure from analysis outputs.

    This function is tailored to the AKTA chromatography analysis script output.
    """
    # Default structure
    now_utc = datetime.now(timezone.utc).isoformat()
    analysis_status = "pending"
    summary = {}
    data_files = {}
    plots = {}
    analysis_metadata = {}

    analysis_results = load_analysis_results(elab_id)

    if analysis_results is None:
        # No analysis JSON found; still try to infer files/plots by pattern
        analysis_status = "pending"
    else:
        status = analysis_results.get("status")
        if status == "success":
            analysis_status = "completed"
        elif status == "failed":
            analysis_status = "failed"
        else:
            analysis_status = "pending"

        # Extract summary-level metrics
        meta = analysis_results.get("metadata", {}) or {}
        analysis_metadata = meta
        num_peaks = meta.get("num_peaks_detected")
        if isinstance(num_peaks, int):
            summary["num_peaks_detected"] = num_peaks

        peaks = meta.get("peaks")
        if isinstance(peaks, list):
            rts = []
            heights = []
            for p in peaks:
                if not isinstance(p, dict):
                    continue
                rt = p.get("retention_time_min")
                ht = p.get("height")
                if isinstance(rt, (int, float)):
                    rts.append(float(rt))
                if isinstance(ht, (int, float)):
                    heights.append(float(ht))
            if rts:
                summary["retention_times_min"] = rts
            if heights:
                summary["peak_heights_mau"] = heights

        akta_source = meta.get("akta_data_source")
        if isinstance(akta_source, str):
            summary["akta_data_source"] = akta_source

        files_processed = analysis_results.get("files_processed")
        if isinstance(files_processed, int):
            summary["files_processed"] = files_processed

        # File paths as reported by analysis script
        plots_block = analysis_results.get("plots", {}) or {}
        data_outputs_block = analysis_results.get("data_outputs", {}) or {}

        if "chromatogram_png" in plots_block:
            plots["chromatogram_png"] = plots_block["chromatogram_png"]
        if "chromatogram_pdf" in plots_block:
            plots["chromatogram_pdf"] = plots_block["chromatogram_pdf"]

        if "timeseries_csv" in data_outputs_block:
            data_files["timeseries_csv"] = data_outputs_block["timeseries_csv"]
        if "peaks_csv" in data_outputs_block:
            data_files["peaks_csv"] = data_outputs_block["peaks_csv"]

        # Also record the main analysis results JSON path
        results_folder = Path("../results").resolve()
        analysis_results_path = results_folder / f"analysis_results_{elab_id}.json"
        data_files["analysis_results_json"] = str(analysis_results_path)

    # If no explicit files were found but we know naming conventions, fill them in
    results_folder_default = Path("../results").resolve()
    if "analysis_results_json" not in data_files:
        data_files["analysis_results_json"] = str(
            results_folder_default / f"analysis_results_{elab_id}.json"
        )
    if "timeseries_csv" not in data_files:
        data_files["timeseries_csv"] = str(
            results_folder_default / f"akta_timeseries_{elab_id}.csv"
        )
    if "peaks_csv" not in data_files:
        data_files["peaks_csv"] = str(
            results_folder_default / f"akta_peaks_{elab_id}.csv"
        )

    if "chromatogram_png" not in plots:
        plots["chromatogram_png"] = str(
            results_folder_default / f"chromatogram_{elab_id}.png"
        )
    if "chromatogram_pdf" not in plots:
        plots["chromatogram_pdf"] = str(
            results_folder_default / f"chromatogram_{elab_id}.pdf"
        )

    return {
        "analysis_status": analysis_status,
        "timestamp": now_utc,
        "summary": summary,
        "data_files": data_files,
        "plots": plots,
        "analysis_metadata": analysis_metadata,
    }



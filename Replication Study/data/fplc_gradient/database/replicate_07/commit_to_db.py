def build_results(elab_id: int) -> dict:
    """Build results JSONB structure from analysis outputs and folder listing."""

    results_folder = Path("../results")
    analysis_data = load_analysis_results(elab_id)

    # Determine analysis status and message from analysis_results JSON
    status_raw = analysis_data.get("status")
    if status_raw == "success":
        analysis_status = "completed"
    elif status_raw in {"failed", "error"}:
        analysis_status = "failed"
    else:
        analysis_status = "pending"

    message = analysis_data.get("message", "")

    # Peaks list (already in suitable structure in analysis_results)
    peaks = analysis_data.get("peaks", [])

    # Simple summary metrics
    n_peaks = len(peaks) if isinstance(peaks, list) else 0
    first_peak_rt = None
    last_peak_rt = None
    if n_peaks > 0:
        try:
            rts = [p.get("retention_time_min") for p in peaks if "retention_time_min" in p]
            rts = [float(rt) for rt in rts if rt is not None]
            if rts:
                first_peak_rt = min(rts)
                last_peak_rt = max(rts)
        except Exception:
            first_peak_rt = None
            last_peak_rt = None

    # Data files and plots from analysis_results structure
    data_files = {}
    plots = {}

    data_outputs = analysis_data.get("data_outputs") or {}
    if isinstance(data_outputs, dict):
        if "chromatogram_csv" in data_outputs:
            data_files["chromatogram_csv"] = data_outputs["chromatogram_csv"]

    plots_dict = analysis_data.get("plots") or {}
    if isinstance(plots_dict, dict):
        chrom = plots_dict.get("chromatogram") or {}
        if isinstance(chrom, dict):
            png = chrom.get("png")
            pdf = chrom.get("pdf")
            if png:
                plots["chromatogram_png"] = png
            if pdf:
                plots["chromatogram_pdf"] = pdf

    # Paths based on expected naming even if analysis_results is missing
    if "chromatogram_csv" not in data_files:
        csv_path = results_folder / f"akta_chromatogram_processed_{elab_id}.csv"
        if csv_path.exists():
            data_files["chromatogram_csv"] = str(csv_path.resolve())

    if "chromatogram_png" not in plots:
        png_path = results_folder / f"chromatogram_{elab_id}.png"
        if png_path.exists():
            plots["chromatogram_png"] = str(png_path.resolve())

    if "chromatogram_pdf" not in plots:
        pdf_path = results_folder / f"chromatogram_{elab_id}.pdf"
        if pdf_path.exists():
            plots["chromatogram_pdf"] = str(pdf_path.resolve())

    # Always include analysis_results JSON path if present
    analysis_results_json_path = results_folder / f"analysis_results_{elab_id}.json"
    if analysis_results_json_path.exists():
        data_files["analysis_results_json"] = str(analysis_results_json_path.resolve())

    results_obj = {
        "analysis_status": analysis_status,
        "analysis_timestamp": datetime.now(timezone.utc).isoformat(),
        "analysis_message": message,
        "summary": {
            "n_peaks": n_peaks,
            "first_peak_rt_min": first_peak_rt,
            "last_peak_rt_min": last_peak_rt,
        },
        "peaks": peaks,
        "data_files": data_files,
        "plots": plots,
        "raw_analysis": analysis_data,
    }

    return results_obj



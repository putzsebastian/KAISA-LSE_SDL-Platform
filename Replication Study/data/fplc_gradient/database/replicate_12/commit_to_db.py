def build_results(elab_id: int) -> dict:
    """Build results JSONB structure from analysis outputs.

    This function inspects the ../results/ folder and, if available, ingests the
    analysis_results_<ID>.json file generated by akta_analysis.py to populate
    summary metrics and peak information.
    """

    results_folder = Path("../results")
    results_folder_resolved = results_folder.resolve()

    analysis_payload = load_analysis_results(elab_id)

    # Default values
    analysis_status = "pending"
    summary: dict = {}
    peaks_list: list = []
    data_files: dict = {}
    plots: dict = {}

    if analysis_payload is not None:
        status_raw = analysis_payload.get("status")
        if status_raw == "success":
            analysis_status = "completed"
        elif status_raw:
            analysis_status = "failed"

        # Peaks and summary metrics
        peaks = analysis_payload.get("peaks") or []
        if isinstance(peaks, list):
            peaks_list = peaks
            n_peaks = len(peaks)
            summary["n_peaks"] = n_peaks
            if n_peaks > 0:
                try:
                    times_min = [p.get("time_min") for p in peaks if isinstance(p.get("time_min"), (int, float))]
                    if times_min:
                        summary["first_peak_time_min"] = float(min(times_min))
                        summary["last_peak_time_min"] = float(max(times_min))
                except Exception:
                    pass
                try:
                    heights = [p.get("height") for p in peaks if isinstance(p.get("height"), (int, float))]
                    if heights:
                        summary["max_peak_height"] = float(max(heights))
                except Exception:
                    pass

        # File paths from analysis payload
        data_outputs = analysis_payload.get("data_outputs", {}) or {}
        if isinstance(data_outputs, dict):
            if "processed_data_csv" in data_outputs:
                data_files["processed_data_csv"] = data_outputs["processed_data_csv"]

        plots_payload = analysis_payload.get("plots", {}) or {}
        if isinstance(plots_payload, dict):
            if "chromatogram" in plots_payload:
                plots["chromatogram"] = plots_payload["chromatogram"]

        # Explicit analysis_results JSON file path
        analysis_results_name = f"analysis_results_{elab_id}.json"
        if (results_folder / analysis_results_name).exists():
            data_files["analysis_results_json"] = str(results_folder_resolved / analysis_results_name)

    # If paths not found via payload, fall back to expected naming in results folder
    processed_csv_name = f"akta_processed_data_{elab_id}.csv"
    processed_csv_path = results_folder_resolved / processed_csv_name
    if "processed_data_csv" not in data_files and processed_csv_path.exists():
        data_files["processed_data_csv"] = str(processed_csv_path)

    plot_name = f"akta_chromatogram_{elab_id}.png"
    plot_path = results_folder_resolved / plot_name
    if "chromatogram" not in plots and plot_path.exists():
        plots["chromatogram"] = str(plot_path)

    results = {
        "analysis_status": analysis_status,
        "analysis_timestamp": datetime.now(timezone.utc).isoformat(),
        "summary": summary,
        "peaks": peaks_list,
        "data_files": data_files,
        "plots": plots,
        "raw_analysis": analysis_payload,
    }

    return results



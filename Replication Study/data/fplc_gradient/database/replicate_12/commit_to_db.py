def parse_numeric(value: str):
    """Extract a numeric value from a string like '25 °C' or '100 mM'.

    Call this ONLY for a single-valued field eLabFTW types as a number. On a text field
    it is destructive - '20 mM NaAc' becomes 20.0 and the buffer identity is gone - and
    on a delimited list it keeps only the first element. When in doubt, store the
    original string unchanged.
    """

    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip()
    if text == "":
        return None

    import re

    # Replace comma decimal separator with dot if it looks like a single number
    if "," in text and ";" not in text:
        # if it matches a pattern like 1,23 or -1,0 treat as decimal comma
        if re.fullmatch(r"[-+]?\d{1,3},\d+", text.replace(" ", "")):
            text = text.replace(",", ".")

    match = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", text)
    if match:
        try:
            return float(match.group(0))
        except ValueError:
            return None
    return None


def parse_field(value, field_type: str | None = None):
    """Route an eLabFTW value by what it IS, not by which parameter it came from.

    Any field may arrive as a delimited list, so the delimiter check comes first.
    """

    if value is None or value == "":
        return None
    if isinstance(value, (list, int, float)):
        return value

    text = str(value).strip()
    if text == "":
        return None

    # a list if a delimiter separates more than one token; "1,5" (decimal comma) is one
    for sep in (";", ","):
        parts = [p.strip() for p in text.split(sep) if p.strip()]
        if len(parts) > 1:
            # Check if this could actually be a decimal-comma single number -> then skip
            if sep == "," and len(parts) == 2:
                joined = "".join(parts)
                if joined.replace(".", "").replace(",", "").replace("+", "").replace("-", "").isdigit():
                    # looks like a single number with decimal comma, don't treat as list
                    break
            # Try to parse all parts as floats; if any fail, keep as strings
            nums = []
            all_numeric = True
            for p in parts:
                try:
                    nums.append(float(p))
                except ValueError:
                    all_numeric = False
                    break
            if all_numeric:
                return nums
            return parts

    # Not a list -> maybe numeric if field_type says so
    if field_type == "number":
        num = parse_numeric(text)
        return num if num is not None else text

    return text  # text stays text


